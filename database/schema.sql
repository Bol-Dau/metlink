-- ============================================================================
-- METLINK Database Schema (Part 1: Core Tables)
-- ============================================================================

BEGIN;

-- Automatically updates the updated_at column whenever a row is edited
CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- ----------------------------------------------------------------------------
-- 1. Admins: Staff accounts that manage the platform
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS admins (
    admin_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username       VARCHAR(50)  NOT NULL UNIQUE,
    password_hash  VARCHAR(255) NOT NULL,
    full_name      VARCHAR(100) NOT NULL,
    email          VARCHAR(100) NOT NULL UNIQUE,
    role           VARCHAR(20)  NOT NULL DEFAULT 'admin',
    is_active      BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at     TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_admins_role
        CHECK (role IN ('super_admin', 'admin', 'market_analyst'))
);

CREATE TRIGGER trg_admins_updated_at
    BEFORE UPDATE ON admins
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- ----------------------------------------------------------------------------
-- 2. Farmers: Tomato growers registered by an admin
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS farmers (
    farmer_id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    phone_number         VARCHAR(20)  NOT NULL UNIQUE,
    name                 VARCHAR(100) NOT NULL,
    location             VARCHAR(100) NOT NULL,
    preferred_language   VARCHAR(10)  NOT NULL DEFAULT 'en',
    registration_source  VARCHAR(20)  NOT NULL DEFAULT 'admin',
    registered_by        BIGINT       NOT NULL,
    is_active            BOOLEAN      NOT NULL DEFAULT TRUE,
    registered_at        TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at           TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_farmers_registered_by
        FOREIGN KEY (registered_by) REFERENCES admins(admin_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,

    CONSTRAINT chk_farmers_language
        CHECK (preferred_language IN ('en', 'rw')),

    CONSTRAINT chk_farmers_source
        CHECK (registration_source IN ('admin', 'ussd'))
);

CREATE TRIGGER trg_farmers_updated_at
    BEFORE UPDATE ON farmers
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- ----------------------------------------------------------------------------
-- 3. Harvest Submissions: Expected harvests sent via USSD by registered farmers
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS harvest_submissions (
    submission_id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farmer_id                  BIGINT         NOT NULL,
    expected_harvest_date      DATE           NOT NULL,
    quantity_kg                DECIMAL(10,2)  NOT NULL,
    tomato_maturity            VARCHAR(20)    NOT NULL,
    has_suitable_preservation  BOOLEAN        NOT NULL,
    location                   VARCHAR(100)   NOT NULL,
    status                     VARCHAR(20)    NOT NULL DEFAULT 'PENDING',
    created_at                 TIMESTAMPTZ    NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_submissions_farmer
        FOREIGN KEY (farmer_id) REFERENCES farmers(farmer_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,

    CONSTRAINT chk_submissions_quantity
        CHECK (quantity_kg > 0),

    CONSTRAINT chk_submissions_maturity
        CHECK (tomato_maturity IN ('GREEN', 'TURNING', 'RIPE')),

    CONSTRAINT chk_submissions_status
        CHECK (status IN ('PENDING', 'PROCESSED', 'CANCELLED'))
);

-- ----------------------------------------------------------------------------
-- 4. Audit Logs: History of actions taken by admins
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS audit_logs (
    log_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    admin_id    BIGINT       NOT NULL,
    action      VARCHAR(50)  NOT NULL,
    entity      VARCHAR(50)  NOT NULL,
    record_id   BIGINT       NOT NULL,
    old_value   TEXT         NULL,
    new_value   TEXT         NULL,
    details     TEXT         NOT NULL,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_audit_logs_admin
        FOREIGN KEY (admin_id) REFERENCES admins(admin_id)
        ON UPDATE CASCADE ON DELETE RESTRICT
);

-- ----------------------------------------------------------------------------
-- 5. Seasonal Information: Rwandan agricultural seasons (A, B, C)
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS seasonal_information (
    season_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    season_name  VARCHAR(50)  NOT NULL,
    start_date   DATE         NOT NULL,
    end_date     DATE         NOT NULL,
    description  TEXT         NOT NULL,
    is_active    BOOLEAN      NOT NULL DEFAULT TRUE,
    created_by   BIGINT       NOT NULL,
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at   TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_seasons_created_by
        FOREIGN KEY (created_by) REFERENCES admins(admin_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,

    CONSTRAINT chk_seasons_dates
        CHECK (end_date >= start_date)
);

CREATE TRIGGER trg_seasons_updated_at
    BEFORE UPDATE ON seasonal_information
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- ----------------------------------------------------------------------------
-- 6. Market Information: Tomato prices and demand across Rwandan markets
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS market_information (
    market_id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    market_name           VARCHAR(100)   NOT NULL,
    location              VARCHAR(100)   NOT NULL,
    average_price_per_kg  DECIMAL(10,2)  NOT NULL,
    demand_level          VARCHAR(10)    NOT NULL,
    source                VARCHAR(50)    NOT NULL,
    is_active             BOOLEAN        NOT NULL DEFAULT TRUE,
    created_by            BIGINT         NOT NULL,
    created_at            TIMESTAMPTZ    NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_market_created_by
        FOREIGN KEY (created_by) REFERENCES admins(admin_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,

    CONSTRAINT chk_market_price
        CHECK (average_price_per_kg >= 0),

    CONSTRAINT chk_market_demand
        CHECK (demand_level IN ('HIGH', 'MEDIUM', 'LOW'))
);

-- ----------------------------------------------------------------------------
-- 7. Decision Rules: Criteria used to advise farmers on when and where to sell
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS decision_rules (
    rule_id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rule_name              VARCHAR(100)   NOT NULL,
    maturity               VARCHAR(20)    NOT NULL,
    price_trend            VARCHAR(20)    NOT NULL,
    demand_level           VARCHAR(20)    NOT NULL,
    preservation_required  BOOLEAN        NOT NULL,
    action                 VARCHAR(30)    NOT NULL,
    waiting_period_days    INTEGER        NULL,
    min_quantity_kg        DECIMAL(10,2)  NULL,
    priority               INTEGER        NOT NULL DEFAULT 1,
    is_active              BOOLEAN        NOT NULL DEFAULT TRUE,
    created_at             TIMESTAMPTZ    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at             TIMESTAMPTZ    NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_rules_maturity
        CHECK (maturity IN ('GREEN', 'TURNING', 'RIPE')),

    CONSTRAINT chk_rules_price_trend
        CHECK (price_trend IN ('RISING', 'STABLE', 'FALLING')),

    CONSTRAINT chk_rules_demand_level
        CHECK (demand_level IN ('HIGH', 'MEDIUM', 'LOW')),

    CONSTRAINT chk_rules_action
        CHECK (action IN ('SELL_NOW', 'STORE_AND_WAIT', 'SEEK_ALTERNATIVE_MARKET')),

    CONSTRAINT chk_rules_waiting_days
        CHECK (waiting_period_days IS NULL OR waiting_period_days >= 0),

    CONSTRAINT chk_rules_min_quantity
        CHECK (min_quantity_kg IS NULL OR min_quantity_kg > 0)
);

DROP TRIGGER IF EXISTS trg_decision_rules_updated_at ON decision_rules;
CREATE TRIGGER trg_decision_rules_updated_at
    BEFORE UPDATE ON decision_rules
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- ----------------------------------------------------------------------------
-- 8. Recommendations: Advice generated for each harvest submission
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS recommendations (
    recommendation_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    submission_id        BIGINT       NOT NULL UNIQUE,
    decision_rule_id     BIGINT       NOT NULL,
    action               VARCHAR(30)  NOT NULL,
    reason               TEXT         NOT NULL,
    waiting_period_days  INTEGER      NULL,
    confidence_level     VARCHAR(10)  NOT NULL,
    created_at           TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_recommendations_submission
        FOREIGN KEY (submission_id) REFERENCES harvest_submissions(submission_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,

    CONSTRAINT fk_recommendations_rule
        FOREIGN KEY (decision_rule_id) REFERENCES decision_rules(rule_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,

    CONSTRAINT chk_recommendations_action
        CHECK (action IN ('SELL_NOW', 'STORE_AND_WAIT', 'SEEK_ALTERNATIVE_MARKET')),

    CONSTRAINT chk_recommendations_waiting_days
        CHECK (waiting_period_days IS NULL OR waiting_period_days >= 0),

    CONSTRAINT chk_recommendations_confidence
        CHECK (confidence_level IN ('HIGH', 'MEDIUM', 'LOW'))
);

-- ----------------------------------------------------------------------------
-- 9. Recommendation Evidence: Point-in-time proof backing each recommendation
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS recommendation_evidence (
    evidence_id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recommendation_id        BIGINT       NOT NULL,
    evidence_type            VARCHAR(20)  NOT NULL,
    market_information_id    BIGINT       NULL,
    seasonal_information_id  BIGINT       NULL,
    decision_rule_id         BIGINT       NULL,
    snapshot                 JSONB        NOT NULL,
    notes                    TEXT         NOT NULL,
    created_at               TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_evidence_recommendation
        FOREIGN KEY (recommendation_id) REFERENCES recommendations(recommendation_id)
        ON UPDATE CASCADE ON DELETE CASCADE,

    CONSTRAINT fk_evidence_market
        FOREIGN KEY (market_information_id) REFERENCES market_information(market_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,

    CONSTRAINT fk_evidence_season
        FOREIGN KEY (seasonal_information_id) REFERENCES seasonal_information(season_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,

    CONSTRAINT fk_evidence_rule
        FOREIGN KEY (decision_rule_id) REFERENCES decision_rules(rule_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,

    CONSTRAINT chk_evidence_type
        CHECK (evidence_type IN ('MARKET', 'SEASONAL', 'RULE'))
);

-- ----------------------------------------------------------------------------
-- 10. SMS Logs: Delivery tracking for advice sent to farmers' phones
-- ----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS sms_logs (
    sms_id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recommendation_id  BIGINT       NOT NULL,
    phone_number       VARCHAR(20)  NOT NULL,
    message            TEXT         NOT NULL,
    status             VARCHAR(20)  NOT NULL DEFAULT 'SENT',
    provider_id        VARCHAR(50)  NULL,
    sent_at            TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,
    delivered_at       TIMESTAMPTZ  NULL,

    CONSTRAINT fk_sms_logs_recommendation
        FOREIGN KEY (recommendation_id) REFERENCES recommendations(recommendation_id)
        ON UPDATE CASCADE ON DELETE RESTRICT,

    CONSTRAINT chk_sms_logs_status
        CHECK (status IN ('SENT', 'DELIVERED', 'FAILED'))
);

COMMIT;
